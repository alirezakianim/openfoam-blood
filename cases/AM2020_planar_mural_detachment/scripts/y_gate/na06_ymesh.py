def layout(g, P):
    """vertex coordinates (D0 units) from the design dict P."""
    N0, N1, N2, k = P["N0"], P["N1"], P["N2"], P["k"]
    p1, p2 = N1 - k, N2 - k; m = N0 - p1 - p2
    V = {}
    V["It"], V["Id"] = np.array([g.xin, .5]), np.array([g.xin, -.5])
    yA1, yA2 = .5 - p1 / N0, -.5 + p2 / N0
    V["Ia"], V["Ib"] = np.array([g.xin, yA1]), np.array([g.xin, yA2])
    xc = P["xc"]
    V["Pt"], V["Pa"], V["Pb"], V["Pd"] = (np.array([xc, .5]), np.array([xc, yA1]),
                                          np.array([xc, yA2]), np.array([xc, -.5]))
    V["F1"], V["F2"] = np.array(P["F1"]), np.array(P["F2"])
    V["T1"], V["T2"] = g.at("top", P["sT1"]), g.at("bot", P["sT2"])
    V["N1"], V["N2"] = g.at("inner", P["sN1"]), g.at("inner", P["sN2"])
    for j, e, nv, w, sc in ((1, g.e1, g.n1, W1, P["sc1"]), (2, g.e2, g.m2, W2, P["sc2"])):
        sgn = 1 if j == 1 else -1          # outer wall side: +n1 for d1, -m2 for d2
        c = sc * e; V[f"Qo{j}"] = c + sgn * 0.5 * w * nv; V[f"Qi{j}"] = c - sgn * 0.5 * w * nv
        frac = k / (N1 if j == 1 else N2)
        V[f"Qx{j}"] = V[f"Qi{j}"] + frac * (V[f"Qo{j}"] - V[f"Qi{j}"])
        c = g.Ld * e; V[f"Oo{j}"] = c + sgn * 0.5 * w * nv; V[f"Oi{j}"] = c - sgn * 0.5 * w * nv
        V[f"Ox{j}"] = V[f"Oi{j}"] + frac * (V[f"Oo{j}"] - V[f"Oi{j}"])
    return V, dict(p1=p1, p2=p2, m=m, k=k)

def counts(g, V, cnt, P):
    hs = P["hscale"]; h = P.get("h_stream", 0.97 * HF)
    L = lambda a, b: np.linalg.norm(V[a] - V[b])
    c = dict(cnt)
    c["nPs"] = max(1, round(L("Ia", "Pa") / h))
    c["nJ"] = max(2, math.ceil(max([L("Pa", "F1"), L("Pb", "F2"), L("Pt", "T1"), L("Pd", "T2")]) / h - 0.3))
    c["n1J"] = max(2, math.ceil(max([P.get("LF1Q", L("F1", "Qx1")), P.get("LT1Q", L("T1", "Qo1")), P.get("LN1Q", L("N1", "Qi1"))]) / h - 0.3))
    c["n2J"] = max(2, math.ceil(max([P.get("LF2Q", L("F2", "Qx2")), P.get("LT2Q", L("T2", "Qo2")), P.get("LN2Q", L("N2", "Qi2"))]) / h - 0.3))
    c["n1S"] = max(1, round(L("Qx1", "Ox1") / h)); c["n2S"] = max(1, round(L("Qx2", "Ox2") / h))
    if hs != 1.0:
        c = {kk: max(1, round(v * hs)) for kk, v in c.items()}
        c["m"] = max(1, c["m"])
    return c

def offset_curve(g, j, t):
    """inner-wall offset into the fluid at distance t, from the upstream tip ray to the d_j cut side."""
    bis = (g.e1 + g.e2) / np.linalg.norm(g.e1 + g.e2)
    a_tip = math.atan2(-bis[1], -bis[0])
    R = g.R1 if j == 1 else g.R2
    a_R = math.atan2(*(R - g.Ca)[::-1])
    def unwrap(x, ref):
        while x - ref > math.pi: x -= 2 * math.pi
        while x - ref < -math.pi: x += 2 * math.pi
        return x
    a_R = unwrap(a_R, a_tip)
    tt = np.linspace(a_tip, a_R, 800)
    arcp = np.stack([g.Ca[0] + (g.ra + t) * np.cos(tt), g.Ca[1] + (g.ra + t) * np.sin(tt)], 1)
    e = g.e1 if j == 1 else g.e2
    end = arcp[-1] + (g.Ld + 1.0) * e
    return np.concatenate([arcp, arcp[-1] + np.linspace(0, 1, 2000)[1:, None] * (end - arcp[-1])]), len(arcp)

def c_outer(g, V, P, j):
    k = P["k"]; Nj = P["N1"] if j == 1 else P["N2"]; w = W1 if j == 1 else W2
    t = k / Nj * w
    oc, na = offset_curve(g, j, t)
    F = V[f"F{j}"]; Q = V[f"Qx{j}"]
    # join point: fraction aJ of the offset apex arc (0 = tip ray, 1 = tangent point)
    iJ = int(round(P[f"aJ{j}"] * (na - 1))); J = oc[iJ]
    tJ = oc[min(iJ + 1, len(oc) - 1)] - oc[max(iJ - 1, 0)]; tJ /= np.linalg.norm(tJ)
    phi = math.radians(P[f"phi{j}"]); tF = np.array([math.cos(phi), math.sin(phi)])
    Lc = np.linalg.norm(J - F); f = P.get(f"ten{j}", 0.4)
    p1 = F + f * Lc * tF; p2 = J - f * Lc * tJ
    s = np.linspace(0, 1, 400)[:, None]
    her = (1 - s) ** 3 * F + 3 * (1 - s) ** 2 * s * p1 + 3 * (1 - s) * s ** 2 * p2 + s ** 3 * J
    iQ = int(np.argmin(np.linalg.norm(oc - Q, axis=1)))
    if iQ <= iJ: raise ValueError("join beyond the cut")
    return np.concatenate([her, oc[iJ + 1:iQ], [Q]])

def build(P, g=None, want_edges=False):
    g = g or Geom(P["Rf1"], P["Rf2"], P["ra"])
    V, cnt = layout(g, P)
    c = dict(P["fixed_counts"]) if P.get("fixed_counts") else counts(g, V, cnt, P)
    sag = P["sag"] or {}
    cache, dictedges = {}, {}
    def edge(a, b, n):
        if (a, b) in cache: return cache[(a, b)][n]
        if (b, a) in cache: return cache[(b, a)][n][::-1]
        raise KeyError
    def make(a, b, n):
        key = f"{a}-{b}"; rkey = f"{b}-{a}"
        if (a, b) in WALL or (b, a) in WALL:
            nm = WALL.get((a, b)) or WALL.get((b, a))
            pts = g.wall_points(nm, V[a], V[b]); kind = ("wall", nm, pts)
        elif key in ("F1-Qx1", "F2-Qx2"):
            pts = c_outer(g, V, P, int(key[1])); kind = ("poly", None, pts)
        elif key in CURVED or rkey in CURVED:
            s_ = sag.get(key, 0.0) if key in sag else -sag.get(rkey, 0.0)
            pts, mid = arc3(V[a], V[b], s_); kind = ("arc", mid, pts) if mid is not None else ("line", None, pts)
        else:
            pts = np.array([V[a], V[b]]); kind = ("line", None, pts)
        cache[(a, b)] = {n: resample(pts, n)}; dictedges[(a, b)] = kind
    blocks = []
    for name, vs, (kx, ky) in BLOCKS:
        nx, ny = c[kx], c[ky]
        for (a, b, n) in ((vs[0], vs[1], nx), (vs[3], vs[2], nx), (vs[0], vs[3], ny), (vs[1], vs[2], ny)):
            if (a, b) not in cache and (b, a) not in cache: make(a, b, n)
            else:
                kk = (a, b) if (a, b) in cache else (b, a)
                if n not in cache[kk]:
                    raise ValueError(f"count clash on edge {a}-{b} in {name}: {n} vs {list(cache[kk])}")
        Pb = block_points(V[vs[0]], V[vs[1]], V[vs[2]], V[vs[3]],
                          edge(vs[0], vs[1], nx), edge(vs[3], vs[2], nx), edge(vs[0], vs[3], ny), edge(vs[1], vs[2], ny))
        blocks.append((name, Pb))
    pts, cells, tag = [], [], []
    base = 0
    for name, X in blocks:
        nj, ni = X.shape[0] - 1, X.shape[1] - 1
        pts.append(X.reshape(-1, 2))
        J, I = np.meshgrid(np.arange(nj), np.arange(ni), indexing="ij")
        p = (base + J * (ni + 1) + I).ravel()
        cells.append(np.stack([p, p + 1, p + ni + 2, p + ni + 1], 1)); tag += [name] * (ni * nj)
        base += (ni + 1) * (nj + 1)
    Pall = np.concatenate(pts); Call = np.concatenate(cells)
    key = np.round(Pall / 1e-10).astype(np.int64)
    uniq, inv = np.unique(key, axis=0, return_inverse=True); inv = inv.ravel()
    Pu = np.zeros((len(uniq), 2)); Pu[inv] = Pall
    out = dict(P=Pu, C=inv[Call], tag=np.array(tag), V=V, c=c, g=g)
    if want_edges: out["edges"] = dictedges
    return out

def evaluate(P, g=None, verbose=False):
    try:
        B = build(P, g)
    except Exception as ex:
        return dict(bad=str(ex))
    m = metrics(B["P"], B["C"])
    A = m["A"]
    r = dict(nc=m["nc"], inv=int((A <= 0).sum()), nomax=m["nomax"], noavg=m["noavg"], n25=m["n25"],
             skmax=m["skmax"], Amin=A.min() / HF ** 2, Amax=A.max() / HF ** 2, emax=m["elen_max"] / HF,
             c=B["c"])
    if verbose:
        tag = B["tag"]; no = m["no"]; worst = {}
        for t in np.unique(tag):
            s = tag[m["own_i"]] == t
            if s.any(): worst[t] = round(float(no[s].max()), 1)
        r["per_block"] = worst
        iw = int(np.argmax(no)); r["worst_at"] = m["fc_i"][iw].round(3).tolist()
        r["Amin_at"] = m["cc"][int(np.argmin(A))].round(3).tolist(); r["Amin_tag"] = tag[int(np.argmin(A))]
        r["Amax_tag"] = tag[int(np.argmax(A))]
        r["skew_i"] = float(m["ski"].max()); r["skew_b"] = float(m["skb"].max())
    return r, B, m
