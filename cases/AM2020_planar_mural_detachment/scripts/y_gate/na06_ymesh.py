#!/usr/bin/env python3
"""na06: asymmetric order-4 planar Y (d1 0.951, d2 0.62, alpha12 83 deg), 15-block
blockMesh blocking with two interior valence-5 vertices F1, F2 (one per stream tube).

Points are generated by an exact replica of OF-13 block::createPoints
(src/mesh/blockMesh/blocks/block/blockCreate.C:45-183, the k = 0 plane) with
lineDivide lambda divisions (lineDivide.C:41-139, simpleGrading 1), arc edges
uniform in angle (arcEdge.C:140) and polyLine edges uniform in arc length
(polyLine.C calcParam/position). Metrics: OF primitiveMeshCheck non-orth and
skewness, vectorised, cross-checked against na03_ymesh.metrics (validated on P73).
Units: D0 = 1 (the dict scales by 58.333e-6 m, sim units S_L 5/3).
"""
import math, sys, json, importlib.util
import numpy as np

TH1, TH2 = 27.0, 56.0            # deflections from the parent axis (deg): large d1 up, small d2 down
W1, W2 = 0.951, 0.62
HF = 0.75 / 58.3333333            # the eps/h = 4 floor, h <= 0.75 um sim, in D0 units

def u(deg):
    r = math.radians(deg); return np.array([math.cos(r), math.sin(r)])

def lin_int(p, d, q, e):
    A = np.array([d, -e]).T; t = np.linalg.solve(A, q - p); return p + t[0] * d

class Geom:
    def __init__(s, Rf1=1.0, Rf2=1.0, ra=0.15, Lp=4.0, Ld=4.0):
        s.e1 = u(TH1); s.n1 = u(TH1 + 90)
        s.e2 = u(-TH2); s.m2 = u(90 - TH2)            # m2: d2 normal pointing to the apex side
        s.Lp, s.Ld, s.Rf1, s.Rf2, s.ra = Lp, Ld, Rf1, Rf2, ra
        z = np.zeros(2)
        # top: y = 0.5 and d1 outer line
        K1 = lin_int(np.array([0, .5]), np.array([1., 0]), z + 0.5 * W1 * s.n1, s.e1)
        t1 = Rf1 * math.tan(math.radians(TH1) / 2)
        s.TS1 = K1 - np.array([t1, 0]); s.TE1 = K1 + t1 * s.e1; s.Cf1 = s.TS1 + np.array([0, Rf1])
        K2 = lin_int(np.array([0, -.5]), np.array([1., 0]), z - 0.5 * W2 * s.m2, s.e2)
        t2 = Rf2 * math.tan(math.radians(TH2) / 2)
        s.TS2 = K2 - np.array([t2, 0]); s.TE2 = K2 + t2 * s.e2; s.Cf2 = s.TS2 - np.array([0, Rf2])
        Ka = lin_int(z - 0.5 * W1 * s.n1, s.e1, z + 0.5 * W2 * s.m2, s.e2)
        half = math.radians(TH1 + TH2) / 2
        ta = ra / math.tan(half)
        s.R1 = Ka + ta * s.e1; s.R2 = Ka + ta * s.e2
        bis = (s.e1 + s.e2) / np.linalg.norm(s.e1 + s.e2)
        s.Ca = Ka + bis * ra / math.sin(half); s.Ka, s.K1, s.K2 = Ka, K1, K2
        s.xin = -Lp
        s.D1o = Ld * s.e1 + 0.5 * W1 * s.n1; s.D1i = Ld * s.e1 - 0.5 * W1 * s.n1
        s.D2o = Ld * s.e2 - 0.5 * W2 * s.m2; s.D2i = Ld * s.e2 + 0.5 * W2 * s.m2
        # dense wall polylines with exact vertices at the tangent points
        def arcpts(c, p0, p1, n=4000, cw=False):
            a0 = math.atan2(*(p0 - c)[::-1]); a1 = math.atan2(*(p1 - c)[::-1]); r = np.linalg.norm(p0 - c)
            if cw:
                while a1 > a0: a1 -= 2 * math.pi
            else:
                while a1 < a0: a1 += 2 * math.pi
            t = np.linspace(a0, a1, n); return np.stack([c[0] + r * np.cos(t), c[1] + r * np.sin(t)], 1)
        def seg(a, b, n=4000):
            return a + np.linspace(0, 1, n)[:, None] * (b - a)
        s.top = np.concatenate([seg(np.array([s.xin, .5]), s.TS1), arcpts(s.Cf1, s.TS1, s.TE1)[1:], seg(s.TE1, s.D1o)[1:]])
        s.bot = np.concatenate([seg(np.array([s.xin, -.5]), s.TS2), arcpts(s.Cf2, s.TS2, s.TE2, cw=True)[1:], seg(s.TE2, s.D2o)[1:]])
        # inner wall, d1 outlet -> apex -> d2 outlet; the apex arc goes CCW about Ca from R1 to R2 the long way? no:
        tipp = s.Ca - bis * ra                                             # must pass the upstream tip
        apa, apb = arcpts(s.Ca, s.R1, s.R2, cw=False), arcpts(s.Ca, s.R1, s.R2, cw=True)
        ap = apa if np.linalg.norm(apa - tipp, axis=1).min() < np.linalg.norm(apb - tipp, axis=1).min() else apb
        s.tip = s.Ca - bis * ra
        s.inner = np.concatenate([seg(s.D1i, s.R1), ap[1:], seg(s.R2, s.D2i)[1:]])
        s.curves = {"top": s.top, "bot": s.bot, "inner": s.inner}
        s.arcs = {"top": (s.TS1, s.TE1, s.Cf1), "bot": (s.TS2, s.TE2, s.Cf2), "inner": (s.R1, s.R2, s.Ca)}
        s.cum = {k: np.concatenate([[0], np.cumsum(np.linalg.norm(np.diff(c, axis=0), axis=1))]) for k, c in s.curves.items()}

    def at(s, name, sv):
        c, cs = s.curves[name], s.cum[name]
        return np.array([np.interp(sv, cs, c[:, 0]), np.interp(sv, cs, c[:, 1])])

    def sof(s, name, p):
        c, cs = s.curves[name], s.cum[name]
        return cs[int(np.argmin(np.linalg.norm(c - p, axis=1)))]

    def wall_points(s, name, p0, p1):
        """dense exact polyline of the wall between two points on it (either direction)."""
        a, b = s.sof(name, p0), s.sof(name, p1)
        c, cs = s.curves[name], s.cum[name]
        lo, hi = min(a, b), max(a, b)
        inside = c[(cs > lo + 1e-12) & (cs < hi - 1e-12)]
        pts = np.concatenate([[s.at(name, lo)], inside, [s.at(name, hi)]])
        return pts if a <= b else pts[::-1]

def resample(pts, n):
    """n divisions uniform in arc length (polyLine.C / arcEdge with lambda = i/n)."""
    sc = np.concatenate([[0], np.cumsum(np.linalg.norm(np.diff(pts, axis=0), axis=1))])
    t = np.linspace(0, 1, n + 1) * sc[-1]
    return np.stack([np.interp(t, sc, pts[:, 0]), np.interp(t, sc, pts[:, 1])], 1)

def arc3(a, b, sag, n=400):
    """arc through a, b and the point mid + sag*|ab|*normal (sag 0 = straight)."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    if abs(sag) < 1e-9:
        return a + np.linspace(0, 1, n)[:, None] * (b - a), None
    L = np.linalg.norm(b - a); t = (b - a) / L; nrm = np.array([-t[1], t[0]])
    m = 0.5 * (a + b) + sag * L * nrm
    # circle through a, m, b
    A = np.array([2 * (m - a), 2 * (b - a)]); rhs = np.array([m @ m - a @ a, b @ b - a @ a])
    c = np.linalg.solve(A, rhs); r = np.linalg.norm(a - c)
    a0 = math.atan2(*(a - c)[::-1]); am = math.atan2(*(m - c)[::-1]); a1 = math.atan2(*(b - c)[::-1])
    def unwrap(x, ref):
        while x - ref > math.pi: x -= 2 * math.pi
        while x - ref < -math.pi: x += 2 * math.pi
        return x
    am = unwrap(am, a0); a1 = unwrap(a1, am)
    tt = np.linspace(a0, a1, n)
    return np.stack([c[0] + r * np.cos(tt), c[1] + r * np.sin(tt)], 1), m

# ---------------- OF-13 block::createPoints, k = 0 plane ----------------
def block_points(p000, p100, p110, p010, E0, E1, E4, E5):
    """E0: v0->v1 (ni+1), E1: v3->v2, E4: v0->v3 (nj+1), E5: v1->v2. lambda = i/n (simpleGrading 1)."""
    ni, nj = len(E0) - 1, len(E4) - 1
    w0 = np.linspace(0, 1, ni + 1); w1 = w0; w4 = np.linspace(0, 1, nj + 1); w5 = w4
    I, J = np.meshgrid(np.arange(ni + 1), np.arange(nj + 1))      # (nj+1, ni+1)
    W0, W1, W4, W5 = w0[I], w1[I], w4[J], w5[J]
    wx1 = (1 - W0) * (1 - W4) + W0 * (1 - W5); wx2 = (1 - W1) * W4 + W1 * W5
    sx = wx1 + wx2; wx1, wx2 = wx1 / sx, wx2 / sx
    wy1 = (1 - W4) * (1 - W0) + W4 * (1 - W1); wy2 = (1 - W5) * W0 + W5 * W1
    sy = wy1 + wy2; wy1, wy2 = wy1 / sy, wy2 / sy
    wz1 = (1 - W0) * (1 - W4); wz2 = W0 * (1 - W5); wz3 = W1 * W5; wz4 = (1 - W1) * W4
    sz = wz1 + wz2 + wz3 + wz4; wz1, wz2, wz3, wz4 = wz1 / sz, wz2 / sz, wz3 / sz, wz4 / sz
    X = lambda a: a[..., None]
    ex1 = p000 + (p100 - p000) * X(W0); ex2 = p010 + (p110 - p010) * X(W1)
    ey1 = p000 + (p010 - p000) * X(W4); ey2 = p100 + (p110 - p100) * X(W5)
    P = (X(wx1) * ex1 + X(wx2) * ex2 + X(wy1) * ey1 + X(wy2) * ey2
         + X(wz1) * p000 + X(wz2) * p100 + X(wz3) * p110 + X(wz4) * p010) / 3
    P = P + X(wx1) * (E0[I] - ex1) + X(wx2) * (E1[I] - ex2) + X(wy1) * (E4[J] - ey1) + X(wy2) * (E5[J] - ey2)
    P[0, :], P[-1, :], P[:, 0], P[:, -1] = E0, E1, E4, E5           # vertices/edges exact
    return P

# ---------------- vectorised OF metrics ----------------
def metrics(P, C):
    P = np.asarray(P); C = np.asarray(C)
    x, y = P[C][..., 0], P[C][..., 1]
    xn, yn = np.roll(x, -1, 1), np.roll(y, -1, 1)
    cr = x * yn - xn * y; A = 0.5 * cr.sum(1)
    cc = np.stack([((x + xn) * cr).sum(1) / (6 * A), ((y + yn) * cr).sum(1) / (6 * A)], 1)
    a = C.ravel(); b = np.roll(C, -1, 1).ravel(); cell = np.repeat(np.arange(len(C)), 4)
    key = np.minimum(a, b).astype(np.int64) * len(P) + np.maximum(a, b)
    o = np.argsort(key, kind="stable"); ks = key[o]
    first = np.ones(len(ks), bool); first[1:] = ks[1:] != ks[:-1]
    idx_first = np.flatnonzero(first)
    cnt = np.diff(np.concatenate([idx_first, [len(ks)]]))
    own_e = o[idx_first]; intern = cnt == 2
    nb_e = o[idx_first[intern] + 1]
    pa, pb = P[a[own_e]], P[b[own_e]]
    fc = 0.5 * (pa + pb); t = pb - pa; S = np.stack([t[:, 1], -t[:, 0]], 1)
    own = cell[own_e]
    # internal
    oi, ni_ = own[intern], cell[nb_e]
    d = cc[ni_] - cc[oi]; Si = S[intern]
    cs = (d * Si).sum(1) / (np.linalg.norm(d, axis=1) * np.linalg.norm(Si, axis=1))
    no = np.degrees(np.arccos(np.clip(cs, -1, 1)))
    def skew(Cpf, dd, SS, pa_, pb_, fc_, fac):
        sv = Cpf - ((SS * Cpf).sum(1) / (SS * dd).sum(1))[:, None] * dd
        nsv = np.linalg.norm(sv, axis=1); svh = sv / (nsv[:, None] + 1e-300)
        fd = np.maximum(fac * np.linalg.norm(dd, axis=1),
                        np.maximum(np.abs((svh * (pa_ - fc_)).sum(1)), np.abs((svh * (pb_ - fc_)).sum(1))))
        return nsv / fd
    ski = skew(fc[intern] - cc[oi], d, Si, pa[intern], pb[intern], fc[intern], 0.2)
    bd = ~intern; Cpf = fc[bd] - cc[own[bd]]; Sb = S[bd]
    nrm = Sb / np.linalg.norm(Sb, axis=1)[:, None]; db = nrm * (nrm * Cpf).sum(1)[:, None]
    skb = skew(Cpf, db, Sb, pa[bd], pb[bd], fc[bd], 0.4)
    elen = np.linalg.norm(t, axis=1)
    return dict(nc=len(C), A=A, cc=cc, no=no, own_i=oi, nb_i=ni_, nomax=no.max(),
                noavg=math.degrees(math.acos(cs.mean())), ski=ski, skb=skb,
                skmax=max(ski.max(), skb.max()), elen_max=elen.max(), n25=int((no > 25).sum()),
                fc_i=fc[intern])

